// Packs apps/render (the Remotion templates) into a TypeScript module the web app
// ships to the render sandbox. Run `npm run render:pack` after editing apps/render;
// CI runs it with --check to make sure the committed module is up to date.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("../apps/render/", import.meta.url).pathname;
const target = new URL("../apps/web/src/lib/render/remotion-source.generated.ts", import.meta.url).pathname;

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = Object.fromEntries(
  ["package.json", "package-lock.json", "tsconfig.json", "smoke.mjs", "stills.mjs", "page.mjs", "cutout.mjs", "track.py", ...walk(join(root, "src")).map((p) => relative(root, p))]
    .sort()
    .map((path) => [path, readFileSync(join(root, path), "utf8")]),
);
const hash = createHash("sha256").update(JSON.stringify(files)).digest("hex").slice(0, 16);
const output = `// Generated by scripts/pack-render.mjs from apps/render. Do not edit.
export const REMOTION_SOURCE_HASH = ${JSON.stringify(hash)};
export const REMOTION_SOURCE_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = (() => {
    try {
      return readFileSync(target, "utf8");
    } catch {
      return "";
    }
  })();
  if (current !== output) {
    console.error("apps/render changed: run `npm run render:pack` and commit the result.");
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
  console.log(`packed ${Object.keys(files).length} files (${hash})`);
}
